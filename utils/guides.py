def render_beginner_guide(key: str, expanded: bool = False) -> None:
    """在模块顶部渲染可折叠小白引导。"""
    guide = GUIDES.get(key)
    if not guide:
        return

    with st.expander(guide["title"], expanded=expanded):
        st.markdown("#### 操作步骤")
        for i, step in enumerate(guide["steps"], 1):
            st.markdown(f"{i}. {step}")

        st.markdown("#### 核心概念（记住这些就够入门）")
        for item in guide["concepts"]:
            st.markdown(f"- {item}")

        st.markdown("#### 易踩坑")
        for item in guide["pitfalls"]:
            st.markdown(f"- ⚠️ {item}")


def render_learning_path_sidebar() -> None:
    """侧边栏展示推荐学习路线。"""
    with st.expander("🗺️ 推荐学习路线", expanded=False):
        st.caption("如果你是新手，建议按这个顺序点模块：")
        for i, (name, tip) in enumerate(LEARNING_PATH, 1):
            st.markdown(f"**{i}. {name}**  \n{tip}")
        st.caption("模块 1、2 可随时用来检查自己上传的表格。")
